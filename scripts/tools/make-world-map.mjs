#!/usr/bin/env node
// Builds apps/web/src/downloads/world-map.ts, the map behind the download page's peer map, from
// Natural Earth (public domain). Run by hand when the map should change; the result is committed,
// so neither the build nor the browser fetches anything.
//
//   node scripts/tools/make-world-map.mjs
//
// Land outlines: 1:110m countries. Country positions (where a peer from that country is drawn):
// the label points of the 1:50m countries, which also has small places such as SG and HK.
// Projection: equirectangular, 1000 wide, latitudes 84°N to 58°S (Antarctica left out).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const BASE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/';
const W = 1000;
const NORTH = 84;
const SOUTH = -58;
const H = Math.round((W * (NORTH - SOUTH)) / 360);
const x = (lon) => ((lon + 180) / 360) * W;
const y = (lat) => ((NORTH - lat) / (NORTH - SOUTH)) * H;
const r1 = (v) => Math.round(v * 10) / 10;

const get = async (name) => (await fetch(BASE + name)).json();
const [small, mid] = await Promise.all([
  get('ne_110m_admin_0_countries.geojson'),
  get('ne_50m_admin_0_countries.geojson'),
]);

const code = (p) => [p.ISO_A2_EH, p.ISO_A2, p.WB_A2].find((c) => typeof c === 'string' && /^[A-Z]{2}$/.test(c));

function ring(coords) {
  const pts = coords.filter((c) => c[1] >= SOUTH - 1).map(([lon, lat]) => [r1(x(lon)), r1(y(Math.max(SOUTH, lat)))]);
  // drop points that land on the previous one after rounding
  const out = pts.filter((p, i) => i === 0 || p[0] !== pts[i - 1][0] || p[1] !== pts[i - 1][1]);
  if (out.length < 3) return '';
  return `M${out.map((p) => p.join(',')).join('L')}Z`;
}

let land = '';
for (const f of small.features) {
  if (f.properties.CONTINENT === 'Antarctica') continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) land += ring(poly[0]);
}

const centroids = {};
for (const f of mid.features) {
  const p = f.properties;
  const c = code(p);
  if (!c || centroids[c]) continue;
  const lon = p.LABEL_X;
  const lat = p.LABEL_Y;
  if (typeof lon !== 'number' || typeof lat !== 'number') continue;
  centroids[c] = [r1(x(lon)), r1(y(lat))];
}

const out = `// Generated by scripts/tools/make-world-map.mjs from Natural Earth (public domain). Do not edit.
// Equirectangular, ${W}×${H}, latitudes ${NORTH}°N to ${-SOUTH}°S.
export const MAP_WIDTH = ${W};
export const MAP_HEIGHT = ${H};
/** All land, one SVG path. */
export const LAND = ${JSON.stringify(land)};
/** Where a country is drawn: its label point, by ISO 3166-1 alpha-2. */
export const CENTROIDS: Record<string, [number, number]> = ${JSON.stringify(centroids)};
`;
const target = fileURLToPath(new URL('../../apps/web/src/downloads/world-map.ts', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${target}: ${(out.length / 1024).toFixed(0)} kB, ${Object.keys(centroids).length} countries`);
